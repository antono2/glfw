// Emit GLFW's generated API and its compile-only C ABI probe.
module glfwgen

import crypto.sha256
import x.json2
import os
import rand

pub const header_files = ['glfw3.h', 'glfw3native.h']

pub struct Pin {
pub:
	version string
	tag     string
	headers map[string]string
}

struct Bindings {
	version     string
	handwritten string
	header      string
	native      string
	previous    string
	types       HeaderTypes
	structs     []HeaderStruct
	callbacks   []CPrototype
	functions   []CPrototype
}

pub fn read_pin(root string) !Pin {
	path := os.join_path(root, 'third_party', 'upstream.json')
	return json2.decode[Pin](os.read_file(path)!)
}

fn read_header(root string, pin Pin, name string) !string {
	content := os.read_file(os.join_path(root, 'third_party', name))!
	hash := sha256.hexhash(content)
	if hash != pin.headers[name] {
		return error('pinned ${name} hash mismatch: ${hash}')
	}
	return content
}

fn read_bindings(root string) !Bindings {
	pin := read_pin(root)!
	header := read_header(root, pin, header_files[0])!
	native := read_header(root, pin, header_files[1])!
	if header_version(header)! != pin.version {
		return error('pinned GLFW version does not match glfw3.h')
	}
	handwritten := os.read_file(os.join_path(root, 'glfw.v'))!
	previous := os.read_file(os.join_path(root, 'glfw_generated.v')) or { '' }
	structs := header_structs(header)!
	raw_callbacks := callbacks(header)!
	mut names := v_names(handwritten + '\n' + previous)
	for declaration in structs {
		if declaration.name !in names {
			names[declaration.name] = declaration.name['GLFW'.len..].to_lower().capitalize()
		}
	}
	mut no_arg_callback := map[string]bool{}
	for callback in raw_callbacks {
		if callback.parameters == 'void' {
			no_arg_callback[callback.name] = true
		}
	}
	return Bindings{
		version:     pin.version
		handwritten: handwritten
		header:      header
		native:      native
		previous:    previous
		types:       HeaderTypes{names, no_arg_callback}
		structs:     structs
		callbacks:   raw_callbacks
		functions:   prototypes(header)!
	}
}

fn (surface Bindings) validate_native(root string) ! {
	mut sources := []string{}
	for platform in os.ls(os.join_path(root, 'native'))! {
		directory := os.join_path(root, 'native', platform)
		if !os.is_dir(directory) {
			continue
		}
		for filename in os.ls(directory)! {
			if filename.ends_with('.v') {
				sources << os.read_file(os.join_path(directory, filename))!
			}
		}
	}
	existing := c_functions(sources.join('\n'))
	mut missing := []string{}
	for declaration in prototypes(surface.native)! {
		if declaration.name !in existing {
			missing << declaration.name
		}
	}
	if missing.len != 0 {
		return error('native API coverage failure: missing ${missing.join(', ')}')
	}
}

fn (surface Bindings) typed_functions() ![]Prototype {
	existing := c_functions(surface.handwritten)
	mut functions := []Prototype{}
	for raw in surface.functions {
		prototype := surface.types.prototype(raw)!
		if raw.name !in existing {
			functions << prototype
		}
	}
	return functions
}

fn (prototype Prototype) signature() (string, string) {
	mut args := []string{}
	for index, kind in prototype.parameters {
		args << 'arg${index} ${kind}'
	}
	suffix := if prototype.return_type == '' { '' } else { ' ${prototype.return_type}' }
	return args.join(', '), suffix
}

fn (surface Bindings) source() !string {
	mut lines := [
		'// Generated by tools/generate.vsh from GLFW ${surface.version}. Do not edit.',
		'// Additional core constants, types, callbacks and wrappers from the GLFW header.',
		'// Regenerate with v run tools/generate.vsh. Raw results follow upstream ownership rules.',
		'module glfw',
		'',
		'import antono2.vulkan as vk',
		'',
		'// GLFW constants. Values come from the pinned upstream header.',
	]
	lines << constants(surface.header, surface.handwritten)!
	lines << ''
	existing_types := handwritten_types(surface.handwritten)
	mut definitions := map[string]HeaderStruct{}
	for declaration in surface.structs {
		definitions[declaration.name] = declaration
	}
	wrapped := v_names(surface.handwritten)
	for c_name, v_name in surface.types.names {
		if c_name in wrapped {
			continue
		}
		declaration := definitions[c_name] or { continue }
		lines << ['pub type ${v_name} = C.${c_name}', '@[typedef]']
		fields := surface.types.struct_fields(declaration)!
		if fields.len == 0 {
			lines << ['pub struct C.${c_name} {}', '']
		} else {
			lines << ['pub struct C.${c_name} {', 'pub:']
			lines << fields
			lines << ['}', '']
		}
	}
	lines << '// Raw callback signatures. Register named functions with C-compatible lifetimes.'
	for raw in surface.callbacks {
		prototype := surface.types.prototype(raw)!
		if raw.name !in existing_types {
			args, suffix := prototype.signature()
			lines << 'pub type ${raw.name} = fn (${args})${suffix}'
		}
	}
	lines << ['', '// Core GLFW functions not already present in the handwritten compatibility API.']
	for prototype in surface.typed_functions()! {
		args, suffix := prototype.signature()
		params := prototype.parameters.join(', ')
		lines << ['', 'fn C.${prototype.name}(${params})${suffix}',
			'pub fn ${snake(prototype.name)}(${args})${suffix} {']
		mut forwarded := []string{}
		for index in 0 .. prototype.parameters.len {
			forwarded << 'arg${index}'
		}
		call := 'C.${prototype.name}(${forwarded.join(', ')})'
		lines << if prototype.return_type == '' { '\t${call}' } else { '\treturn ${call}' }
		lines << '}'
	}
	return lines.join('\n') + '\n'
}

// temporary_directory reserves a unique workspace for compiling or formatting.
pub fn temporary_directory(prefix string) !string {
	directory := os.join_path(os.temp_dir(), '${prefix}-${rand.ulid()}')
	os.mkdir(directory)!
	return directory
}

// generate either writes the formatted bindings or verifies the committed snapshot.
pub fn generate(root string, compiler string, check bool) ! {
	surface := read_bindings(root)!
	surface.validate_native(root)!
	directory := temporary_directory('glfw-generated')!
	defer { os.rmdir_all(directory) or {} }
	file := os.join_path(directory, 'glfw_generated.v')
	os.write_file(file, surface.source()!)!
	format := os.exec([compiler, 'fmt', '-w', file])
	if format.exit_code != 0 {
		return error('could not format generated bindings: ${format.output}')
	}
	result := os.read_file(file)!
	if check {
		if result != surface.previous.replace('\r\n', '\n') {
			return error('glfw_generated.v is stale. Run v run tools/generate.vsh')
		}
		println('GLFW generated binding is current')
	} else {
		output := os.join_path(root, 'glfw_generated.v')
		os.write_file(output, result)!
		println('wrote ${output}')
	}
}

// abi_probe produces calls that the compiler must type check and link without opening GLFW.
pub fn abi_probe(root string) !(string, int) {
	functions := read_bindings(root)!.typed_functions()!
	mut lines := ['module main', 'import os
import rand', 'import antono2.glfw', 'fn main() {',
		'    if os.args.len > 100000 {']
	for prototype in functions {
		mut args := []string{}
		for kind in prototype.parameters {
			args << if kind.starts_with('&') || kind == 'voidptr' || kind.starts_with('GLFW')
				|| kind.starts_with('vk.') {
				'unsafe { nil }'
			} else {
				'0'
			}
		}
		prefix := if prototype.return_type != '' { '_ = ' } else { '' }
		lines << '        ${prefix}glfw.${snake(prototype.name)}(${args.join(', ')})'
	}
	lines << ['    }', '}']
	return lines.join('\n') + '\n', functions.len
}
